import { describe, expect, it } from "vitest";
import { discoverFileRoutes } from "./extract-file-routes.ts";
import { emitRouteTree } from "./emit-route-tree.ts";

describe("emitRouteTree", () => {
  it("emits a complete routeTree.gen.ts source", () => {
    const routes = discoverFileRoutes([
      "__root.route.ts",
      "index.route.ts",
      "about.route.ts",
      "cats.route.ts",
      "cats.index.route.ts",
      "cats.new.route.ts",
      "cats.$id.route.ts",
      "$.route.ts",
    ]);
    const src = emitRouteTree(routes);

    // Header
    expect(src).toContain("Generated by meowter");

    // All routes imported
    expect(src).toContain(`import { Route as RootRoute } from "./routes/__root.route.ts";`);
    expect(src).toContain(`import { Route as CatsIdRoute } from "./routes/cats.$id.route.ts";`);
    expect(src).toContain(`import { Route as SplatRoute } from "./routes/$.route.ts";`);

    // Bindings — own paths preserved
    expect(src).toContain("const rootRoute = bindFileRootRoute(RootRoute);");
    expect(src).toContain(`const catsRoute = bindFileRoute(CatsRoute, rootRoute, "cats");`);
    expect(src).toContain(`const catsIdRoute = bindFileRoute(CatsIdRoute, catsRoute, ":id");`);
    expect(src).toContain(`const catsIndexRoute = bindFileRoute(CatsIndexRoute, catsRoute, "");`);

    // Tree composition uses addChildren
    expect(src).toContain("export const routeTree = rootRoute.addChildren([");
    // catsRoute is a parent → nested addChildren
    expect(src).toMatch(/catsRoute\.addChildren\(\[\s+catsIndexRoute/);

    // Router export
    expect(src).toContain("export type AppPaths = RouterPaths<typeof routeTree>;");
    expect(src).toContain("export const router = createRouter({");
    expect(src).toContain('basepath: VITE_ENV?.BASE_URL ?? "/"');
  });

  it("throws when __root.route.ts is missing", () => {
    const routes = discoverFileRoutes(["about.route.ts"]);
    expect(() => emitRouteTree(routes)).toThrow(/missing root route/);
  });
});
