/**
 * Emit the source of `routeTree.gen.ts` from a discovered route set.
 *
 * Output shape:
 * ```ts
 * // Generated header
 * import { ... } from "meowter";
 * import { Route as RootRoute } from "./routes/__root.route.ts";
 * // ... per-route imports
 *
 * const rootRoute = bindFileRootRoute(RootRoute);
 * const indexRoute = bindFileRoute(IndexRoute, rootRoute, "");
 * const catsRoute = bindFileRoute(CatsRoute, rootRoute, "cats");
 * // ...
 *
 * export const routeTree = rootRoute.addChildren([
 *   indexRoute,
 *   catsRoute.addChildren([catsIndexRoute, catsNewRoute, catsIdRoute]),
 *   // ...
 * ]);
 *
 * export type AppPaths = RouterPaths<typeof routeTree>;
 *
 * const VITE_ENV = (import.meta as { env?: { BASE_URL?: string } }).env;
 * export const router = createRouter({
 *   routeTree,
 *   basepath: VITE_ENV?.BASE_URL ?? "/",
 * });
 * ```
 */
import { groupByParent, type DiscoveredRoute } from "./extract-file-routes.ts";

const HEADER = `// Generated by meowter — DO NOT EDIT.
// Re-run \`vite\` (with the meowterFileRoutes plugin) or \`meowter-routes gen-tree\`
// to refresh after adding, renaming, or removing a \`*.route.ts\` file.
`;

function camelize(exportName: string): string {
  // CatsIdRoute → catsIdRoute
  return exportName.charAt(0).toLowerCase() + exportName.slice(1);
}

function quote(s: string): string {
  return `"${s.replace(/"/g, '\\"')}"`;
}

export interface EmitOptions {
  /**
   * Module specifier for `meowter`. Tests can override; default is the
   * package name.
   */
  meowterSpecifier?: string;
}

export function emitRouteTree(
  routes: readonly DiscoveredRoute[],
  options: EmitOptions = {},
): string {
  const meowter = options.meowterSpecifier ?? "meowter";
  const lines: string[] = [];

  lines.push(HEADER);

  // Imports
  lines.push(
    `import { bindFileRootRoute, bindFileRoute, createRouter, type RouterPaths } from ${quote(meowter)};`,
  );
  for (const r of routes) {
    lines.push(`import { Route as ${r.exportName} } from ${quote(r.importPath)};`);
  }
  lines.push("");

  // Bind each route to its parent
  const root = routes.find((r) => r.isRoot);
  if (!root) {
    throw new Error(
      'meowter: missing root route file. Expected "__root.route.ts" in the routes directory.',
    );
  }

  const rootIdent = camelize(root.exportName);
  lines.push(`const ${rootIdent} = bindFileRootRoute(${root.exportName});`);

  for (const r of routes) {
    if (r.isRoot) continue;
    const parent = r.parentKey;
    const parentExport = routes.find((x) => x.key === parent)?.exportName;
    if (!parentExport) {
      throw new Error(`meowter: route "${r.filePath}" has no parent — missing __root.route.ts?`);
    }
    const parentIdent = camelize(parentExport);
    const ident = camelize(r.exportName);
    lines.push(
      `const ${ident} = bindFileRoute(${r.exportName}, ${parentIdent}, ${quote(r.ownPath)});`,
    );
  }

  lines.push("");

  // Compose the tree via nested addChildren calls
  const groups = groupByParent(routes);

  function renderChildren(parentKey: string, depth: number): string {
    const kids = groups.get(parentKey) ?? [];
    if (kids.length === 0) return "";
    const indent = "  ".repeat(depth);
    const innerIndent = "  ".repeat(depth + 1);
    const parts = kids.map((kid) => {
      const ident = camelize(kid.exportName);
      const grandkids = renderChildren(kid.key, depth + 1);
      if (grandkids) {
        return `${innerIndent}${ident}.addChildren([\n${grandkids}\n${innerIndent}])`;
      }
      return `${innerIndent}${ident}`;
    });
    void indent;
    return parts.join(",\n");
  }

  const topChildren = renderChildren(root.key, 0);
  if (topChildren) {
    lines.push(`export const routeTree = ${rootIdent}.addChildren([`);
    lines.push(topChildren);
    lines.push(`]);`);
  } else {
    lines.push(`export const routeTree = ${rootIdent};`);
  }

  lines.push("");
  lines.push("export type AppPaths = RouterPaths<typeof routeTree>;");
  lines.push("");
  lines.push("const VITE_ENV = (import.meta as { env?: { BASE_URL?: string } }).env;");
  lines.push("export const router = createRouter({");
  lines.push("  routeTree,");
  lines.push('  basepath: VITE_ENV?.BASE_URL ?? "/",');
  lines.push("});");
  lines.push("");

  return lines.join("\n");
}
